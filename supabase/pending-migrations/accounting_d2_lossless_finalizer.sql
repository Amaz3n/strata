    'ap_account', coalesce(b.accounting_coding->'ap_account', case when b.qbo_ap_account_id is not null then jsonb_build_object('id', b.qbo_ap_account_id, 'name', b.qbo_ap_account_name) end),
    'counterparty', coalesce(b.accounting_coding->'counterparty', b.accounting_coding->'vendor', case when b.company_id is null and b.qbo_vendor_id is not null then jsonb_build_object('id', b.qbo_vendor_id, 'name', b.qbo_vendor_name) end),
