   or (b.qbo_ap_account_id is not null and b.accounting_coding->'ap_account' is null)
   or (b.company_id is null and b.qbo_vendor_id is not null and b.accounting_coding->'counterparty' is null)
   or (b.qbo_class_id is not null and b.accounting_coding#>'{dimensions,class}' is null);

-- Fail closed for Patagonia's immutable connection identity and for every
-- non-null coding disagreement. A reviewer must choose the authoritative value;
-- this migration never guesses which account should receive customer money.
do $$
declare
  v_target_rows bigint;
  v_conflicts bigint;
begin
  select count(*) into v_target_rows
  from public.orgs o
  join public.accounting_connections c on c.org_id = o.id
  where o.name = 'Patagonia Development LLC' and c.provider = 'qbo' and c.status = 'active'
    and c.external_account_id = '9341456671106880';
  if v_target_rows <> 1 then
    raise exception 'D2 blocked: Patagonia active QBO realm identity changed (expected exactly one row)';
  end if;

  select
    (select count(*) from public.project_expenses e
      where e.qbo_expense_account_id is not null
        and e.accounting_coding#>>'{expense_account,id}' is not null
        and e.accounting_coding#>>'{expense_account,id}' is distinct from e.qbo_expense_account_id)
    +
    (select count(*) from public.vendor_bills b
      where b.qbo_expense_account_id is not null
        and b.accounting_coding#>>'{expense_account,id}' is not null
        and b.accounting_coding#>>'{expense_account,id}' is distinct from b.qbo_expense_account_id)
  into v_conflicts;
  if v_conflicts > 0 then
    raise exception 'D2 blocked: % non-null legacy/neutral expense-account conflicts require disposition', v_conflicts;
  end if;
end
$$;

commit;
