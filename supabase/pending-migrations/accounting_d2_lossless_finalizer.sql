-- Fill only absent neutral keys. `coalesce` deliberately preserves every
-- existing neutral value; non-null disagreements are reviewed, never overwritten.
update public.project_expenses e
set accounting_coding =
  (coalesce(e.accounting_coding, '{}'::jsonb) - 'vendor' - 'class')
  || jsonb_strip_nulls(jsonb_build_object(
    'transaction_type', coalesce(e.accounting_coding->'transaction_type', to_jsonb(e.qbo_transaction_type)),
    'expense_account', coalesce(e.accounting_coding->'expense_account', case when e.qbo_expense_account_id is not null then jsonb_build_object('id', e.qbo_expense_account_id, 'name', e.qbo_expense_account_name) end),
    'payment_account', coalesce(e.accounting_coding->'payment_account', case when e.qbo_payment_account_id is not null then jsonb_build_object('id', e.qbo_payment_account_id, 'name', e.qbo_payment_account_name) end),
    'ap_account', coalesce(e.accounting_coding->'ap_account', case when e.qbo_ap_account_id is not null then jsonb_build_object('id', e.qbo_ap_account_id, 'name', e.qbo_ap_account_name) end),
    'counterparty', coalesce(e.accounting_coding->'counterparty', e.accounting_coding->'vendor', case when e.vendor_company_id is null and e.qbo_vendor_id is not null then jsonb_build_object('id', e.qbo_vendor_id, 'name', e.qbo_vendor_name) end),
    'dimensions', coalesce(e.accounting_coding->'dimensions', '{}'::jsonb) || case
      when coalesce(e.accounting_coding#>'{dimensions,class}', e.accounting_coding->'class') is not null then jsonb_build_object('class', coalesce(e.accounting_coding#>'{dimensions,class}', e.accounting_coding->'class'))
      when e.qbo_class_id is not null then jsonb_build_object('class', jsonb_build_object('id', e.qbo_class_id, 'name', e.qbo_class_name))
      else '{}'::jsonb end
  ))
