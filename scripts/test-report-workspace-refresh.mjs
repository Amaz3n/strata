import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import { chromium, expect } from "@playwright/test"
import babel from "next/dist/compiled/babel/core.js"
import compiler from "babel-plugin-react-compiler"

const built = await Bun.build({ entrypoints: ["tests/fixtures/report-workspace-refresh/ui.jsx"], target: "browser", define: { "process.env.NODE_ENV": '"production"', "process.env": "{}" }, plugins: [{ name: "report-workspace-refresh", setup(builder) {
  builder.onLoad({ filter: /report-workspace\.tsx$/ }, async ({ path }) => ({ loader: "tsx", contents: babel.transformSync(await readFile(path, "utf8"), { filename: path, configFile: false, babelrc: false, parserOpts: { plugins: ["typescript", "jsx"] }, plugins: [[compiler, { target: "19" }]] }).code }))
  builder.onResolve({ filter: /^@\/app\/\(app\)\/reports\/actions$/ }, () => ({ path: "actions", namespace: "fixture" }))
  builder.onLoad({ filter: /^actions$/, namespace: "fixture" }, () => ({ loader: "js", contents: 'export function previewReportAction(input){return new Promise(resolve=>(window.reportReads??=[]).push({input,resolve}))} export async function snapshotReportAction(input,fingerprint,name){(window.reportSnapshots??=[]).push({input,fingerprint,name});return "fixture-snapshot"} export async function saveReportAction(){throw Error("Unexpected save")}' }))
  builder.onResolve({ filter: /^@\/app\/\(app\)\/books\/actions$/ }, () => ({ path: "book-actions", namespace: "fixture" }))
  builder.onLoad({ filter: /^book-actions$/, namespace: "fixture" }, () => ({ loader: "js", contents: 'export async function loadAccountActivityAction(){throw Error("Unexpected activity read")}' }))
  builder.onResolve({ filter: /^next\/navigation$/ }, () => ({ path: "navigation", namespace: "fixture" }))
  builder.onLoad({ filter: /^navigation$/, namespace: "fixture" }, () => ({ loader: "js", contents: 'export function useRouter(){return {push(){},refresh(){}}} export function useSearchParams(){return new URLSearchParams()} export function usePathname(){return "/reports/fixture"}' }))
} }] })
assert.ok(built.success, built.logs.join("\n"))
const bundle = await built.outputs[0].text()
const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch: request => new URL(request.url).pathname === "/bundle.js" ? new Response(bundle, { headers: { "content-type": "text/javascript" } }) : new Response('<html><body><div id="root"></div><script type="module" src="/bundle.js"></script></body></html>', { headers: { "content-type": "text/html" } }) })
let browser
try {
  browser = await chromium.launch({ headless: true })
  const page = await browser.newPage(), errors = [], blocked = [], origin = `http://127.0.0.1:${server.port}`
  page.on("pageerror", error => { errors.push(error.message); console.error(error.message) })
  await page.route("**/*", route => new URL(route.request().url()).origin === origin ? route.continue() : (blocked.push(route.request().url()), route.abort()))
  await page.goto(origin)
  await expect.poll(() => page.locator("body").innerText()).not.toBe("")
  assert.deepEqual(errors, [])
  await expect(page.getByText("Original server row", { exact: true })).toBeVisible()
  await page.evaluate(() => window.reportFixture.refresh())
  await expect(page.getByText("Fresh server row", { exact: true })).toBeVisible()
  assert.equal(await page.evaluate(() => window.reportReads?.length ?? 0), 0, "server refresh needs no duplicate preview")
  await page.getByRole("button", { name: "Export", exact: true }).click()
  await page.getByRole("menuitem", { name: "Save snapshot", exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.reportSnapshots?.length)).toBe(1)
  assert.equal(await page.evaluate(() => window.reportSnapshots[0].fingerprint), "fresh-fingerprint", "snapshot creation must match the refreshed server rows")
  await page.getByRole("button", { name: "Sort by Name", exact: true }).click()
  await expect(page.getByRole("columnheader", { name: "Name" })).toHaveAttribute("aria-sort", "ascending")
  await page.evaluate(() => window.reportFixture.refresh())
  await expect(page.getByRole("columnheader", { name: "Name" })).toHaveAttribute("aria-sort", "ascending")
  await expect(page.getByRole("button", { name: "Undo customization", exact: true })).toBeEnabled()
  const toggle = page.getByRole("checkbox", { name: "Include optional rows" })
  await toggle.check()
  await expect.poll(() => page.evaluate(() => window.reportReads?.length)).toBe(1)
  await page.evaluate(() => window.reportFixture.resolve(0, "Filtered preview row"))
  await expect(page.getByText("Filtered preview row", { exact: true })).toBeVisible()
  await page.evaluate(() => window.reportFixture.refresh())
  await expect(toggle).toBeChecked()
  await expect(page.getByText("Filtered preview row", { exact: true })).toBeVisible()
  await toggle.uncheck()
  await expect(page.getByText("Fresh server row", { exact: true })).toBeVisible()
  await toggle.check()
  await expect.poll(() => page.evaluate(() => window.reportReads.length)).toBe(2)
  await toggle.uncheck()
  await page.evaluate(() => window.reportFixture.resolve(1, "Stale preview row"))
  await expect(page.getByText("Stale preview row", { exact: true })).toHaveCount(0)
  await expect(page.getByText("Fresh server row", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Refresh report", exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.reportReads.length)).toBe(3)
  await page.evaluate(() => window.reportFixture.resolve(2, "Manually refreshed row"))
  await expect(page.getByText("Manually refreshed row", { exact: true })).toBeVisible()
  assert.deepEqual(errors, [])
  assert.deepEqual(blocked, [])
  console.log("Report workspace adopts refreshed server rows, preserves edited filters, and ignores stale previews")
} finally { await browser?.close(); server.stop(true) }
