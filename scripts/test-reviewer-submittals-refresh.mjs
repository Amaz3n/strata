import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import { chromium, expect } from "@playwright/test"
import babel from "next/dist/compiled/babel/core.js"
import compiler from "babel-plugin-react-compiler"
const built = await Bun.build({ entrypoints: ["tests/fixtures/reviewer-submittals-refresh/ui.jsx"], target: "browser", define: { "process.env.NODE_ENV": '"production"' }, plugins: [{ name: "reviewer-submittals-refresh", setup(builder) {
  builder.onLoad({ filter: /reviewer-submittals-tab\.tsx$/ }, async ({ path }) => ({ loader: "tsx", contents: babel.transformSync(await readFile(path, "utf8"), { filename: path, configFile: false, babelrc: false, parserOpts: { plugins: ["typescript", "jsx"] }, plugins: [[compiler, { target: "19" }]] }).code }))
  builder.onResolve({ filter: /^\.\/actions$/ }, args => args.importer.includes("/app/r/") ? { path: "actions", namespace: "fixture" } : undefined)
  builder.onLoad({ filter: /^actions$/, namespace: "fixture" }, () => ({ loader: "js", contents: 'export function decideReviewerStepAction(token,form){return new Promise(resolve=>(window.fixtureDecisions??=[]).push({token,step:form.get("step_id"),resolve}))} export function loadReviewerQueueAction(token){return new Promise(resolve=>(window.fixtureQueueReads??=[]).push({token,resolve}))} export function listReviewerSubmittalItemsAction(token,id){return new Promise(resolve=>(window.submittalReads??=[]).push({token,id,resolve}))}' }))
  builder.onResolve({ filter: /^next\/navigation$/ }, () => ({ path: "navigation", namespace: "fixture" }))
  builder.onLoad({ filter: /^navigation$/, namespace: "fixture" }, () => ({ loader: "js", contents: 'export function useRouter(){return {refresh(){window.fixtureRefreshes=(window.fixtureRefreshes??0)+1}}}' }))
} }] })
assert.ok(built.success, built.logs.join("\n"))
const bundle = await built.outputs[0].text()
const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch: request => new URL(request.url).pathname === "/bundle.js" ? new Response(bundle, { headers: { "content-type": "text/javascript" } }) : new Response('<html><body><div id="root"></div><script type="module" src="/bundle.js"></script></body></html>', { headers: { "content-type": "text/html" } }) })
let browser
try {
  browser = await chromium.launch({ headless: true })
  const page = await browser.newPage(), errors = [], blocked = [], origin = `http://127.0.0.1:${server.port}`
  page.on("pageerror", error => errors.push(error.message))
  await page.route("**/*", route => new URL(route.request().url()).origin === origin ? route.continue() : (blocked.push(route.request().url()), route.abort()))
  const notes = page.getByPlaceholder("Review notes, exceptions, or resubmission instructions")
  const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await page.goto(origin)
  await expect.poll(() => page.evaluate(() => window.submittalReads?.length)).toBe(2)
  await notes.first().fill("Unsubmitted reviewer notes")
  await page.getByRole("combobox").first().click()
  await page.getByRole("option", { name: "Reject", exact: true }).click()
  await page.locator('input[type="file"]').first().setInputFiles({ name: "draft-markup.pdf", mimeType: "application/pdf", buffer: Buffer.from("fixture markup") })
  await page.evaluate(() => window.submittalFixture.resolve(0, "Initial first document"))
  await expect(page.getByText("#1 Initial first document", { exact: true })).toBeVisible()
  await settle()
  assert.equal(await page.evaluate(() => window.submittalReads.length), 2, "one completion must not duplicate another pending document read")
  await page.evaluate(() => window.submittalFixture.refresh())
  await expect(page.getByText("Submittal #1: Updated first submittal", { exact: true })).toBeVisible()
  await expect(notes.first()).toHaveValue("Unsubmitted reviewer notes")
  await expect(page.getByRole("combobox").first()).toHaveText("Reject")
  assert.equal(await page.locator('input[type="file"]').first().evaluate(input => input.files[0]?.name), "draft-markup.pdf")
  await expect.poll(() => page.evaluate(() => window.submittalReads.length)).toBe(4)
  await page.evaluate(() => window.submittalFixture.resolve(3, "Current second document"))
  await expect(page.getByText("#1 Current second document", { exact: true })).toBeVisible()
  await page.evaluate(() => window.submittalFixture.resolve(1, "Stale second document"))
  await settle()
  await expect(page.getByText("#1 Stale second document", { exact: true })).toHaveCount(0)
  await page.evaluate(() => window.submittalFixture.empty())
  await expect(page.getByText("No submittals waiting on your review", { exact: true })).toBeVisible()
  await page.evaluate(() => window.submittalFixture.resolve(2, "Removed document"))
  await settle()
  await expect(page.getByText("#1 Removed document", { exact: true })).toHaveCount(0)
  await page.evaluate(() => window.submittalFixture.switchPortal())
  await expect.poll(() => page.evaluate(() => window.submittalReads.length)).toBe(6)
  await expect(notes.first()).toHaveValue("")
  await expect(page.getByRole("combobox").first()).toHaveText("Approve")
  assert.equal(await page.locator('input[type="file"]').first().evaluate(input => input.files.length), 0)
  assert.deepEqual(await page.evaluate(() => window.submittalReads.slice(4).map(read => read.token)), ["reviewer-b", "reviewer-b"])
  await page.evaluate(() => window.submittalFixture.history())
  await expect(page.getByRole("heading", { name: "Review history" })).toBeVisible()
  await settle()
  assert.equal(await page.evaluate(() => window.submittalReads.length), 6, "history needs no hidden document reads")
  await page.evaluate(() => window.submittalFixture.duplicate())
  await expect.poll(() => page.evaluate(() => window.submittalReads.length)).toBe(7)
  await page.evaluate(() => window.submittalFixture.resolve(6, "Shared document"))
  await expect(page.getByText("#1 Shared document", { exact: true })).toHaveCount(2)
  await page.evaluate(() => window.submittalFixture.resolve(4, "Old portal document"))
  await settle()
  await expect(page.getByText("#1 Old portal document", { exact: true })).toHaveCount(0)
  for (const oldFirst of [true, false]) {
    await page.goto(origin)
    await expect.poll(() => page.evaluate(() => window.submittalReads?.length)).toBe(2)
    await page.evaluate(() => window.submittalFixture.switchPortal())
    await expect.poll(() => page.evaluate(() => window.submittalReads.length)).toBe(4)
    if (oldFirst) {
      await page.evaluate(() => window.submittalFixture.resolve(0, "Private old document"))
      await settle()
      await expect(page.getByText("#1 Private old document", { exact: true })).toHaveCount(0)
    }
    await page.evaluate(() => window.submittalFixture.resolve(2, "Current portal document"))
    await expect(page.getByText("#1 Current portal document", { exact: true })).toBeVisible()
    if (!oldFirst) {
      await page.evaluate(() => window.submittalFixture.resolve(0, "Private old document"))
      await settle()
      await expect(page.getByText("#1 Current portal document", { exact: true })).toBeVisible()
      await expect(page.getByText("#1 Private old document", { exact: true })).toHaveCount(0)
    }
  }
  await page.goto(origin)
  await expect.poll(() => page.evaluate(() => window.submittalReads?.length)).toBe(2)
  await notes.first().fill("Notes preserved while review returns")
  await page.getByRole("button", { name: "Return review", exact: true }).first().click()
  await expect.poll(() => page.evaluate(() => window.fixtureDecisions?.length)).toBe(1)
  await page.evaluate(() => window.fixtureDecisions[0].resolve())
  await expect.poll(() => page.evaluate(() => window.fixtureQueueReads?.length)).toBe(1)
  await page.evaluate(() => window.submittalFixture.refresh())
  await expect(page.getByText("Submittal #1: Updated first submittal", { exact: true })).toBeVisible()
  await page.evaluate(() => window.fixtureQueueReads[0].resolve([]))
  await expect(page.getByRole("button", { name: "Return review", exact: true }).first()).toBeEnabled()
  await expect(page.getByText("Submittal #1: Updated first submittal", { exact: true })).toBeVisible()
  await expect(notes.first()).toHaveValue("Notes preserved while review returns")
  assert.equal(await page.evaluate(() => window.fixtureRefreshes ?? 0), 0)
  await page.goto(origin)
  await expect.poll(() => page.evaluate(() => window.submittalReads?.length)).toBe(2)
  await page.getByRole("button", { name: "Return review", exact: true }).first().click()
  await expect.poll(() => page.evaluate(() => window.fixtureDecisions?.length)).toBe(1)
  await page.evaluate(() => window.submittalFixture.switchPortal())
  await expect.poll(() => page.evaluate(() => window.submittalReads.length)).toBe(4)
  await page.evaluate(() => window.fixtureDecisions[0].resolve())
  await settle()
  assert.equal(await page.evaluate(() => window.fixtureQueueReads?.length ?? 0), 0, "old portal decisions must not reload the new workspace")
  assert.equal(await page.evaluate(() => window.fixtureRefreshes ?? 0), 0)
  await expect(notes.first()).toHaveValue("")
  await page.getByRole("button", { name: "Return review", exact: true }).first().click()
  await expect.poll(() => page.evaluate(() => window.fixtureDecisions.length)).toBe(2)
  await page.evaluate(() => window.fixtureDecisions[1].resolve())
  await expect.poll(() => page.evaluate(() => window.fixtureQueueReads?.length)).toBe(1)
  await page.evaluate(() => window.fixtureQueueReads[0].resolve([]))
  await expect(page.getByText("No submittals waiting on your review", { exact: true })).toBeVisible()
  assert.equal(await page.evaluate(() => window.fixtureRefreshes), 1, "current review completion still refreshes the server workspace")
  assert.deepEqual(errors, [])
  assert.deepEqual(blocked, [])
  console.log("Reviewer submittals adopt fresh queues, preserve drafts, deduplicate reads, ignore stale documents, and reset portal identity")
} finally { await browser?.close(); server.stop(true) }
