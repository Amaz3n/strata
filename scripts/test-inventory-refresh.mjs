import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import { chromium, expect } from "@playwright/test"
import babel from "next/dist/compiled/babel/core.js"
import compiler from "babel-plugin-react-compiler"

const built = await Bun.build({ entrypoints: ["tests/fixtures/inventory-refresh/ui.jsx"], target: "browser", define: { "process.env.NODE_ENV": '"production"', "process.env": "{}" }, plugins: [{ name: "inventory-refresh", setup(builder) {
  builder.onLoad({ filter: /inventory-workspace\.tsx$/ }, async ({ path }) => ({ loader: "tsx", contents: babel.transformSync(await readFile(path, "utf8"), { filename: path, configFile: false, babelrc: false, parserOpts: { plugins: ["typescript", "jsx"] }, plugins: [[compiler, { target: "19" }]] }).code }))
  builder.onResolve({ filter: /^@\/app\/\(app\)\/books\/actions$/ }, () => ({ path: "actions", namespace: "fixture" }))
  builder.onLoad({ filter: /^actions$/, namespace: "fixture" }, () => ({ loader: "js", contents: 'export function loadInventoryWorkspaceAction(){return new Promise((resolve,reject)=>(window.inventoryReads??=[]).push({resolve,reject}))} function write(input,kind){return new Promise((resolve,reject)=>(window.inventoryWrites??=[]).push({input,kind,resolve,reject}))} export const enableProjectInventoryAction=input=>write(input,"enable"); export const completeProjectInventoryAction=input=>write(input,"complete")' }))
  builder.onResolve({ filter: /^@\/components\/books\/(inventory-allocation|warranty-accounting)$/ }, ({path}) => ({ path:path.split("/").at(-1), namespace:"fixture" }))
  builder.onLoad({ filter: /^(inventory-allocation|warranty-accounting)$/, namespace:"fixture" }, () => ({loader:"jsx",contents:'export function InventoryAllocation({projectId}){return <p>Allocation for {projectId}</p>} export function WarrantyReserveEstimate({projectId}){return <p>Reserve for {projectId}</p>}' }))
  builder.onResolve({ filter: /^sonner$/ }, () => ({ path: "toast", namespace: "fixture" }))
  builder.onLoad({ filter: /^toast$/, namespace: "fixture" }, () => ({ loader: "js", contents: 'export const toast={error(message){(window.inventoryToasts??=[]).push(message)},success(message){(window.inventoryToasts??=[]).push(message)}}' }))
} }] })
assert.ok(built.success, built.logs.join("\n"))
const bundle = await built.outputs[0].text()
const server = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch: request => new URL(request.url).pathname === "/bundle.js" ? new Response(bundle, { headers: { "content-type": "text/javascript" } }) : new Response('<html><body><div id="root"></div><script type="module" src="/bundle.js"></script></body></html>', { headers: { "content-type": "text/html" } }) })
let browser
try {
  browser = await chromium.launch({ headless: true })
  const page = await browser.newPage(), errors = [], blocked = [], origin = `http://127.0.0.1:${server.port}`
  page.on("pageerror", error => errors.push(error.message))
  await page.route("**/*", route => new URL(route.request().url()).origin === origin ? route.continue() : (blocked.push(route.request().url()), route.abort()))
  const policy = {effectiveOn:"2026-09-01",completedOn:null,soldOn:null}
  async function open() { await page.goto("about:blank"); await page.goto(origin); await expect(page.getByRole("button",{name:"Adopt owned inventory accounting"})).toBeVisible() }
  async function refresh(id,policy) { await page.evaluate(({id,policy}) => window.inventoryFixture.refresh({id,name:id,policy}),{id,policy}) }
  async function submit(name="Adopt owned inventory accounting") { await page.locator('input[name="date"]').fill("2026-10-01"); await page.locator('input[name="evidenceUrl"]').fill("https://example.test/evidence"); await page.getByRole("button",{name}).click() }
  await open()
  await page.locator('input[name="date"]').fill("2026-10-01")
  await refresh("first",policy)
  await expect(page.getByText("Build costs capitalized from 2026-09-01")).toBeVisible()
  await expect(page.locator('input[name="date"]')).toHaveValue("2026-10-01")
  await refresh("first",{...policy,completedOn:"2026-10-02"})
  await expect(page.getByText("Completed inventory since 2026-10-02")).toBeVisible()
  await expect(page.getByRole("button",{name:"Record completed home"})).toHaveCount(0)
  await refresh("first",{...policy,soldOn:"2026-10-03"})
  await expect(page.getByText("Sold 2026-10-03",{exact:true})).toBeVisible()
  await open()
  await submit()
  await expect.poll(() => page.evaluate(() => window.inventoryWrites?.length)).toBe(1)
  assert.deepEqual(await page.evaluate(() => window.inventoryWrites[0].input),{projectId:"first",effectiveOn:"2026-10-01",evidenceUrl:"https://example.test/evidence"})
  await page.evaluate(() => window.inventoryWrites[0].resolve({success:true}))
  await expect.poll(() => page.evaluate(() => window.inventoryReads?.length)).toBe(1)
  await page.evaluate(policy => window.inventoryReads[0].resolve({success:true,data:[{id:"first",name:"First",policy}]}),policy)
  await expect(page.getByRole("button",{name:"Record completed home"})).toBeEnabled()
  await submit("Record completed home")
  await expect.poll(() => page.evaluate(() => window.inventoryWrites.length)).toBe(2)
  assert.equal(await page.evaluate(() => window.inventoryWrites[1].kind),"complete")
  await page.evaluate(() => window.inventoryWrites[1].resolve({success:true}))
  await expect.poll(() => page.evaluate(() => window.inventoryReads.length)).toBe(2)
  await page.evaluate(policy => window.inventoryReads[1].resolve({success:true,data:[{id:"first",name:"First",policy}]}),{...policy,completedOn:"2026-10-01"})
  await expect(page.getByText("Completed inventory since 2026-10-01")).toBeVisible()
  await expect(page.getByRole("button",{name:"Record completed home"})).toHaveCount(0)
  await open()
  await submit()
  await expect.poll(() => page.evaluate(() => window.inventoryWrites?.length)).toBe(1)
  await refresh("second",null)
  await expect(page.getByText("Reserve for second")).toBeVisible()
  await expect(page.locator('input[name="date"]')).toHaveValue("")
  await page.evaluate(() => window.inventoryWrites[0].resolve({success:true}))
  await page.waitForTimeout(100)
  assert.equal(await page.evaluate(() => window.inventoryReads?.length ?? 0),0,"obsolete writes must not start a refresh")
  assert.equal(await page.evaluate(() => window.inventoryToasts?.length ?? 0),0,"obsolete writes must not toast")
  await open()
  await submit()
  await page.evaluate(() => window.inventoryWrites[0].resolve({success:true}))
  await expect.poll(() => page.evaluate(() => window.inventoryReads?.length)).toBe(1)
  await refresh("first",{...policy,soldOn:"2026-10-03"})
  await page.evaluate(policy => window.inventoryReads[0].resolve({success:true,data:[{id:"first",name:"First",policy}]}),policy)
  await expect(page.getByText("Sold 2026-10-03",{exact:true})).toBeVisible()
  await expect(page.getByRole("button",{name:"Record completed home"})).toHaveCount(0)
  await open()
  await submit()
  await page.evaluate(() => window.inventoryWrites[0].reject(new Error("Write unavailable")))
  await expect.poll(() => page.evaluate(() => window.inventoryToasts?.at(-1))).toBe("Write unavailable")
  await expect(page.getByRole("button",{name:"Adopt owned inventory accounting"})).toBeEnabled()
  await expect(page.locator('input[name="date"]')).toHaveValue("2026-10-01")
  await submit()
  await expect.poll(() => page.evaluate(() => window.inventoryWrites.length)).toBe(2)
  await page.evaluate(() => window.inventoryFixture.unmount())
  await expect(page.getByText("Inventory removed")).toBeVisible()
  await page.evaluate(() => window.inventoryWrites[1].reject(new Error("Obsolete rejection")))
  await page.waitForTimeout(100)
  assert.equal(await page.evaluate(() => window.inventoryToasts.length),1)
  assert.deepEqual(errors, [])
  assert.deepEqual(blocked, [])
  console.log("Inventory adopts refreshed policies, preserves same-project drafts, resets project switches, ignores obsolete work, and handles rejected writes")
} finally { await browser?.close(); server.stop(true) }
