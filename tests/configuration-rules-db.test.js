const assert = require("node:assert/strict")
const test = require("node:test")
const fs = require("node:fs")
const { PGlite } = require("@electric-sql/pglite")
const org = "00000000-0000-4000-8000-000000000001"
const other = "00000000-0000-4000-8000-000000000002"
const a = "00000000-0000-4000-8000-000000000003"
const b = "00000000-0000-4000-8000-000000000004"
const foreign = "00000000-0000-4000-8000-000000000005"

test("configuration migration enforces organization integrity and blocks browser table access", async (t) => {
  const db = new PGlite()
  t.after(() => db.close())
  await db.exec("create role anon; create role authenticated; create role service_role bypassrls; create table orgs(id uuid primary key); create table app_users(id uuid primary key); create table selection_options(id uuid primary key, org_id uuid not null references orgs(id), name text, parent_option_id uuid, community_id uuid, is_archived boolean not null default false, is_available boolean not null default true);")
  await db.exec(fs.readFileSync(require.resolve("../supabase/migrations/20261003013000_selection_configuration_rules.sql"), "utf8"))
  await db.query("insert into orgs(id) values($1),($2)", [org, other])
  await db.query("insert into selection_options(id,org_id) values($1,$4),($2,$4),($3,$5)", [a, b, foreign, org, other])
  const insert = (source, target, kind = "requires") => db.query("insert into selection_configuration_rules(org_id,source_option_id,target_option_id,kind) values($1,$2,$3,$4)", [org, source, target, kind])
  await insert(a, b)
  await assert.rejects(insert(a, foreign), /configuration_rule_target_fk/)
  await assert.rejects(insert(a, a), /cannot require or exclude itself/)
  await assert.rejects(insert(a, b, "excludes"), /impossible configuration/)
  await assert.rejects(insert(a, b), /configuration_rule_pair_unique/)
  await db.exec("set role authenticated")
  await assert.rejects(db.query("select * from selection_configuration_rules"), /permission denied/)
  await assert.rejects(insert(b, a), /permission denied/)
  await db.exec("reset role; set role service_role")
  await insert(b, a)
  assert.equal((await db.query("select count(*)::int n from selection_configuration_rules")).rows[0].n, 2)
})

test("rule writes reject transitive contradictions, inherit overrides and enforce authoring bounds", async (t) => {
  const db = new PGlite()
  t.after(() => db.close())
  await db.exec("create role anon; create role authenticated; create role service_role bypassrls; create table orgs(id uuid primary key); create table app_users(id uuid primary key); create table selection_options(id uuid primary key, org_id uuid not null references orgs(id), name text, parent_option_id uuid, community_id uuid, is_archived boolean not null default false, is_available boolean not null default true);")
  await db.exec(fs.readFileSync(require.resolve("../supabase/migrations/20261003013000_selection_configuration_rules.sql"), "utf8"))
  await db.query("insert into orgs(id) values($1)", [org])
  const ids = Array.from({ length: 210 }, (_, i) => `00000000-0000-4000-8000-${String(i + 100).padStart(12, "0")}`)
  await db.query("insert into selection_options(id,org_id) select unnest($1::uuid[]),$2", [ids, org])
  const insert = (source, target, kind = "requires") => db.query("insert into selection_configuration_rules(org_id,source_option_id,target_option_id,kind) values($1,$2,$3,$4)", [org, source, target, kind])
  await insert(ids[0], ids[1])
  await insert(ids[1], ids[2])
  await assert.rejects(insert(ids[2], ids[0], "excludes"), /impossible configuration/)
  // A requirement added later must also consider pre-existing exclusions.
  await insert(ids[2], ids[3], "excludes")
  await assert.rejects(insert(ids[0], ids[3]), /impossible configuration/)
  // Valid cycles are allowed; changing a member into an exclusion is not.
  await insert(ids[2], ids[0])
  await assert.rejects(db.query("update selection_configuration_rules set kind='excludes' where source_option_id=$1 and target_option_id=$2", [ids[1], ids[2]]), /impossible configuration/)
  assert.equal((await db.query("select kind from selection_configuration_rules where source_option_id=$1 and target_option_id=$2", [ids[1], ids[2]])).rows[0].kind, "requires")
  // A community override inherits the base's transitive requirements.
  await db.query("update selection_options set parent_option_id=$1, community_id=$2 where id=$3", [ids[0], other, ids[4]])
  await assert.rejects(insert(ids[4], ids[2], "excludes"), /impossible configuration/)
  await assert.rejects(insert(ids[4], ids[0]), /cannot require or exclude itself/)
  await assert.rejects(insert(ids[5], ids[4]), /source option community/)
  await db.query("update selection_options set is_archived=true where id=$1", [ids[6]])
  await assert.rejects(insert(ids[0], ids[6]), /Restore archived options/)
  // A rejected write never leaves behind a partial rule.
  assert.equal((await db.query("select count(*)::int n from selection_configuration_rules")).rows[0].n, 4)
  await assert.rejects(db.query("update selection_options set community_id=$1 where id=$2", [other, ids[0]]), /participates in configuration rules/)
  await assert.rejects(db.query("update selection_options set parent_option_id=$1 where id=$2", [ids[5], ids[1]]), /participates in configuration rules/)
  await assert.rejects(db.query("update selection_options set is_available=false where id=$1", [ids[2]]), /participates in configuration rules/)
  await assert.rejects(db.query("update selection_options set is_archived=true where id=$1", [ids[2]]), /participates in configuration rules/)
  await db.query("update selection_options set name='Updated label', community_id=community_id where id=$1", [ids[0]])
  // A base option must also be protected when only its override has explicit rules.
  await db.query("update selection_options set parent_option_id=$1, community_id=$2 where id=$3", [ids[7], other, ids[8]])
  await insert(ids[8], ids[9])
  await assert.rejects(db.query("update selection_options set is_archived=true where id=$1", [ids[7]]), /participates in configuration rules/)
  await assert.rejects(db.query("delete from selection_options where id=$1", [ids[7]]), /participates in configuration rules/)
  await assert.rejects(db.query("delete from selection_options where id=$1", [ids[8]]), /participates in configuration rules/)
  await db.query("delete from selection_options where id=$1", [ids[209]])
  await db.query("update selection_options set is_available=false where id=$1", [ids[208]])
  await assert.rejects(insert(ids[0], ids[208]), /Restore unavailable options/)
  await db.exec("delete from selection_configuration_rules")
  // The newly changed source can be valid by itself while making an ancestor impossible.
  await insert(ids[0], ids[1])
  await insert(ids[0], ids[2], "excludes")
  await assert.rejects(insert(ids[1], ids[2]), /impossible configuration/)
  await db.exec("delete from selection_configuration_rules")
  await db.query("update selection_options set is_archived=false, is_available=true, parent_option_id=null, community_id=null")
  await db.query("insert into selection_configuration_rules(org_id,source_option_id,target_option_id,kind) select $1,$2,unnest($3::uuid[]),'excludes'", [org, ids[0], ids.slice(1, 201)])
  await assert.rejects(insert(ids[0], ids[201], "excludes"), /at most 200/)
  // Updating an existing rule at the limit remains valid.
  await db.query("update selection_configuration_rules set target_option_id=$1 where source_option_id=$2 and target_option_id=$3", [ids[201], ids[0], ids[1]])
  assert.equal((await db.query("select count(*)::int n from selection_configuration_rules")).rows[0].n, 200)
  await db.exec("set role authenticated")
  await assert.rejects(db.query("select * from selection_configuration_rule_locks"), /permission denied/)
  await assert.rejects(db.query("select validate_selection_configuration_rule()"), /permission denied/)
})
