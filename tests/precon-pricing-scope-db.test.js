const assert = require("node:assert/strict");
const test = require("node:test");
const fs = require("node:fs");
const path = require("node:path");
const { randomUUID } = require("node:crypto");
let PGlite;
try { ({ PGlite } = require(process.env.ARC_TEST_PGLITE_MODULE || "@electric-sql/pglite")); } catch {}
test("pricing scope revision is atomic, preserves history and rejects stale/foreign/closed writes", { skip: !PGlite }, async t => {
  const db = new PGlite(); t.after(() => db.close());
  const migration = name => fs.readFileSync(path.join(__dirname, "../supabase/migrations", name), "utf8");
  await db.exec(fs.readFileSync(path.join(__dirname, "fixtures/bid-pricing-schema.sql"), "utf8"));
  await db.exec(migration("20260921121014_bid_pricing_decisions_and_scope_revisions.sql"));
  await db.exec(`
    create table prospects(id uuid primary key, org_id uuid, status text);
    alter table projects add org_id uuid, add prospect_id uuid;
    create table precon_workspaces(id uuid primary key default gen_random_uuid(), org_id uuid, prospect_id uuid, version integer, brief jsonb, updated_by uuid);
    alter table bid_packages add prospect_id uuid;
    alter table bid_scope_items alter column id set default gen_random_uuid();
    alter table bid_scope_items add position integer, add details text, add unit text, add cost_code_id uuid, add created_by uuid;
    alter table bid_addenda add title text, add message text, add created_by uuid;
  `);
  await db.exec(migration("20261001122200_precon_pricing_scope_revision.sql"));
  const org = randomUUID(), lead = randomUUID(), pkg = randomUUID(), scope = randomUUID(), row = randomUUID(), user = randomUUID();
  const worksheet = { rows: [{ id: row, description: "Revised slab", quantity: 240, unit: "sf", notes: "Reinforced", unit_cost_cents: 2500 }], requests: [{ package_id: pkg, row_ids: [row], scope_signature: "old", quote: { total_cents: 123000 } }] };
  await db.query("insert into prospects values($1,$2,'estimating')", [lead, org]);
  await db.query("insert into bid_packages(id,org_id,prospect_id,status,scope) values($1,$2,$3,'draft','Old slab')", [pkg, org, lead]);
  await db.query("insert into bid_scope_items(id,org_id,bid_package_id,item_type,description,quantity) values($1,$2,$3,'base','Old slab',120)", [scope, org, pkg]);
  await db.query("update bid_packages set status='open' where id=$1", [pkg]);
  await db.query("insert into precon_workspaces(org_id,prospect_id,version,brief) values($1,$2,4,$3)", [org, lead, { pricing_revision: 2, pricing_worksheet: worksheet }]);
  const revise = (version = 4, signature = "new", packageId = pkg) => db.query("select revise_precon_pricing_scope($1,$2,$3,$4,$5,$6,'Added reinforced slab area') result", [org, lead, packageId, user, version, signature]);
  await assert.rejects(revise(3), /changed in another session/);
  const foreign = randomUUID();
  await db.query("insert into bid_packages(id,org_id,status) values($1,$2,'open')", [foreign, org]);
  await assert.rejects(revise(4, "new", foreign), /does not belong/);
  assert.equal((await db.query("select count(*)::int n from bid_addenda")).rows[0].n, 0);
  const result = (await revise()).rows[0].result;
  assert.equal(result.version, 5);
  assert.equal(result.worksheet.requests[0].scope_signature, "new");
  assert.equal(result.worksheet.requests[0].quote, null);
  assert.equal(result.worksheet.rows[0].unit_cost_cents, 2500);
  assert.deepEqual((await db.query("select scope_revision,status from bid_packages where id=$1", [pkg])).rows[0], { scope_revision: 2, status: "open" });
  assert.equal((await db.query("select snapshot->'scope'->0->>'description' old from bid_scope_revisions where bid_package_id=$1", [pkg])).rows[0].old, "Old slab");
  assert.equal(Number((await db.query("select quantity from bid_scope_items where bid_package_id=$1", [pkg])).rows[0].quantity), 240);
  assert.equal((await db.query("select brief->>'pricing_revision' v from precon_workspaces")).rows[0].v, "2");
  await assert.rejects(revise(5, "new"), /already matches/);
  await db.exec("create function fail_scope() returns trigger language plpgsql as $$begin raise exception 'fixture scope failure'; end$$; create trigger fail_scope before insert on bid_scope_items for each row execute function fail_scope();");
  await assert.rejects(revise(5, "next"), /fixture scope failure/);
  assert.equal((await db.query("select scope_revision from bid_packages where id=$1", [pkg])).rows[0].scope_revision, 2);
  assert.equal((await db.query("select count(*)::int n from bid_addenda")).rows[0].n, 1);
  assert.equal((await db.query("select version from precon_workspaces")).rows[0].version, 5);
  await db.query("update prospects set status='won' where id=$1", [lead]);
  await assert.rejects(revise(5, "next"), /Only an open deal/);
  await db.query("update prospects set status='pricing' where id=$1", [lead]);
  const project = randomUUID();
  await db.query("insert into projects(id,org_id,prospect_id,phase) values($1,$2,$3,'delivery')", [project,org,lead]);
  await assert.rejects(revise(5, "next"), /active project/);
  await db.exec("drop trigger fail_scope on bid_scope_items");
  await db.query("update projects set phase='precon' where id=$1", [project]);
  await db.query("update bid_packages set project_id=$1,prospect_id=null where id=$2", [project,pkg]);
  assert.equal((await revise(5, "linked-project")).rows[0].result.version, 6);
  assert.equal((await db.query("select has_function_privilege('authenticated','revise_precon_pricing_scope(uuid,uuid,uuid,uuid,integer,text,text)','execute') allowed")).rows[0].allowed, false);
});
